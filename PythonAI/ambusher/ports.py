from __future__ import annotations

from typing import Iterable, Protocol

from .domain import TacticalPoint, Vec2


class NavigationPort(Protocol):
    def route(self, start: Vec2, goal: Vec2) -> tuple[Vec2, ...] | None: ...
    def route_cost(self, start: Vec2, goal: Vec2) -> float | None: ...


class TacticalWorldPort(Protocol):
    def tactical_points(self) -> Iterable[TacticalPoint]: ...
    def is_available(self, point_id: str, owner_id: str, now: float) -> bool: ...
    def reserve(self, point_id: str, owner_id: str, now: float, ttl: float) -> bool: ...
    def release(self, owner_id: str) -> None: ...


class ClockPort(Protocol):
    def now(self) -> float: ...

